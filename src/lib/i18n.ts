// Map from language name (as stored in localStorage) to translation object
const LANG_MAP: Record<string, Translations> = {
  Arabic: ar,
  Russian: ru,
  Chinese: zh,
  "Chinese (Simplified)": zh,
  "Chinese (Traditional)": zh,
  Spanish: es,
  French: fr,
  German: de,
  Turkish: tr,
  Kyrgyz: ky,
  Portuguese: pt,
  "Portuguese (Brazil)": pt,
};

// Map from browser locale prefix to translation
const LOCALE_MAP: Record<string, Translations> = {
  ar: ar,
  ru: ru,
  zh: zh,
  es: es,
  fr: fr,
  de: de,
  tr: tr,
  ky: ky,
  pt: pt,
};

export function getTranslations(langName?: string | null): Translations {
  if (!langName || langName === "auto") {
    // Auto-detect from browser
    if (typeof navigator !== "undefined") {
      const prefix = navigator.language.split("-")[0].toLowerCase();
      return LOCALE_MAP[prefix] ?? en;
    }
    return en;
  }
  return LANG_MAP[langName] ?? en;
}

export type { Translations as T };
